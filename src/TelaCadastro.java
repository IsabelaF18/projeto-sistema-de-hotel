    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
if (jTextField1.getText().trim().isEmpty()
        || jTextField2.getText().trim().isEmpty()
        || jTextField3.getText().trim().isEmpty()
        || jComboBox1.getSelectedIndex() == 0
        || jComboBox2.getSelectedIndex() == 0) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Preencha todos os campos antes de confirmar!");

} else {
    String nome = jTextField1.getText();
    String telefone = jTextField2.getText();
    String email = jTextField3.getText();
    String quarto = jComboBox1.getSelectedItem().toString();
    String pagamento = jComboBox2.getSelectedItem().toString();

    TelaConfirmacao confirmacao = new TelaConfirmacao(
            nome, telefone, email, quarto, pagamento);

    confirmacao.setLocationRelativeTo(null);
    confirmacao.setVisible(true);
    this.dispose();
}
    }//GEN-LAST:event_jButton2ActionPerformed

